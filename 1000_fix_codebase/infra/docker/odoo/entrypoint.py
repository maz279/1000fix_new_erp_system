#!/usr/bin/env python3
"""1000fix/odoo container entrypoint (R01 re-audit 2026-10-22).

1. DE-11: refuse to start (exit 42) unless FIX_ENV names an environment of
   infra/environments.yaml (copied into the image - the ladder is the single
   source). FIX_ENV=local additionally applies libs/py/fix_env_guard: its
   assert_local() over the standard endpoint variables, and the same
   loopback/compose-name rule on the database HOST this image connects to.
2. REPO-15: the odoo conf is GENERATED at start, never baked or hand-written:
   addons_path from tooling/scripts/generate-odoo-conf.py build_addons_path()
   (the one addons_path builder), the database from HOST / PORT / USER /
   PASSWORD (the official-image contract infra/compose uses; PG* fall back).
   It lands in $ODOO_RC (default /etc/odoo/odoo.conf), mode 0600, owned by the
   non-root odoo user - it carries the database password.
3. Arguments starting with '-' (compose: `--load=base,rpc,web,cd_entity_config`)
   go to odoo-bin after `-c <conf>`; a leading `odoo`/`odoo-bin` is dropped;
   an odoo-bin sub-command (`shell`, `db`, ...) keeps its position. Anything
   else is exec'd as a plain command - after the same guard.
"""

from __future__ import annotations

import configparser
import importlib.util
import io
import os
import secrets
import sys
import time
from pathlib import Path

ROOT = Path(os.environ.get("FIX_ROOT", "/opt/1000fix"))
CONF = Path(os.environ.get("ODOO_RC", "/etc/odoo/odoo.conf"))
DATA_DIR = os.environ.get("ODOO_DATA_DIR", "/var/lib/odoo")
ODOO_BIN = ROOT / "vendor" / "odoo" / "odoo-bin"
# Same list as generate-odoo-conf and the compose `--load` (RPC error hardening).
SERVER_WIDE_MODULES = "base,rpc,web,cd_entity_config"
DE11_EXIT = 42


def refuse(reason: str) -> None:
    print(f"DE-11: refusing to start: {reason}", file=sys.stderr)
    sys.exit(DE11_EXIT)


def known_environments() -> list[str]:
    import yaml

    data = yaml.safe_load((ROOT / "infra" / "environments.yaml").read_text(encoding="utf-8"))
    return [e["name"] for e in data.get("environments", [])]


def db_settings() -> dict[str, str]:
    env = os.environ
    return {
        "db_host": env.get("HOST") or env.get("PGHOST") or "postgres",
        "db_port": env.get("PORT") or env.get("PGPORT") or "5432",
        "db_user": env.get("USER") or env.get("PGUSER") or "odoo",
        "db_password": env.get("PASSWORD") or env.get("PGPASSWORD") or "",
    }


def guard() -> str:
    """DE-11 - the environment this container runs as, or exit 42."""
    fix_env = os.environ.get("FIX_ENV", "").strip()
    names = known_environments()
    if not fix_env:
        refuse(f"FIX_ENV is not set (must be one of: {', '.join(names)})")
    if fix_env not in names:
        refuse(f"FIX_ENV={fix_env!r} is not an environment of infra/environments.yaml")
    if fix_env == "local":
        from libs.py.fix_env_guard import assert_local, endpoint_violation

        assert_local()  # exits 42 itself on a non-local endpoint variable
        reason = endpoint_violation("HOST", db_settings()["db_host"], None)
        if reason:
            refuse(f"{reason}. Fix the environment and restart.")
    return fix_env


def addons_path() -> str:
    spec = importlib.util.spec_from_file_location(
        "generate_odoo_conf", ROOT / "tooling" / "scripts" / "generate-odoo-conf.py"
    )
    if spec is None or spec.loader is None:
        raise RuntimeError("generate-odoo-conf.py missing from the image")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    return ",".join(str((ROOT / p).resolve()) for p in gen.build_addons_path().split(","))


def write_conf(fix_env: str) -> None:
    options = {
        "addons_path": addons_path(),
        "server_wide_modules": SERVER_WIDE_MODULES,
        "data_dir": DATA_DIR,
        **db_settings(),
        # inside the container; compose publishes the port on 127.0.0.1 only
        "http_interface": "0.0.0.0",  # noqa: S104 - container-internal bind
        # PE-002: the database list / manager only ever on local
        "list_db": str(fix_env == "local"),
        # never Odoo's default 'admin': unset = an unguessable one-off value
        "admin_passwd": os.environ.get("ODOO_ADMIN_PASSWORD") or secrets.token_urlsafe(32),
    }
    if os.environ.get("ODOO_WORKERS"):
        options["workers"] = os.environ["ODOO_WORKERS"]
    cfg = configparser.ConfigParser(interpolation=None)
    cfg["options"] = options
    buf = io.StringIO()
    buf.write(
        f"# GENERATED by {Path(__file__).name} at container start (REPO-15) - FIX_ENV={fix_env}\n"
    )
    cfg.write(buf)
    CONF.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(CONF, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(buf.getvalue())


def wait_for_db(timeout: float) -> None:
    import psycopg2

    s = db_settings()
    deadline = time.monotonic() + timeout
    while True:
        try:
            psycopg2.connect(
                dbname="postgres",
                host=s["db_host"],
                port=s["db_port"],
                user=s["db_user"],
                password=s["db_password"],
                connect_timeout=3,
            ).close()
            return
        except psycopg2.OperationalError as exc:
            if time.monotonic() >= deadline:
                print(
                    f"entrypoint: database {s['db_host']}:{s['db_port']} unreachable "
                    f"after {timeout:.0f}s - {str(exc).strip()}",
                    file=sys.stderr,
                )
                sys.exit(1)
            time.sleep(1)


def main(argv: list[str]) -> None:
    fix_env = guard()
    write_conf(fix_env)
    if argv and argv[0] in ("odoo", "odoo-bin"):
        argv = argv[1:]
    if argv and not argv[0].startswith("-"):
        # odoo-bin sub-commands = the odoo/cli modules (server, shell, db, i18n ...)
        commands = {p.stem for p in (ODOO_BIN.parent / "odoo" / "cli").glob("*.py")}
        if argv[0] in commands - {"__init__", "command"}:
            sub, rest = argv[0], argv[1:]
            # an entrypoint's job is to exec: fixed odoo-bin path, no shell involved
            os.execv(sys.executable, [sys.executable, str(ODOO_BIN), sub, "-c", str(CONF), *rest])  # noqa: S606
        # the container's own command (e.g. bash) - reached only past the DE-11 guard
        os.execvp(argv[0], argv)  # noqa: S606
    wait_for_db(float(os.environ.get("ODOO_DB_WAIT", "30")))
    os.execv(sys.executable, [sys.executable, str(ODOO_BIN), "-c", str(CONF), *argv])  # noqa: S606


if __name__ == "__main__":
    main(sys.argv[1:])

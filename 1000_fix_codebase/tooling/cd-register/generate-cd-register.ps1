# =============================================================================
# 1000fix-erp - tooling/cd-register/generate-cd-register.ps1
# P01-M05-T03/T05 - transcribe the BE-005 6 issued register (331 rows) into
# the machine-readable tooling/cd-register/cd-register.yaml, and verify it.
#
# Source of truth: BE-005 6 (issued 2026-08-18, rule CDR-11: generated, not
# transcribed-by-hand). This script re-generates the machine form and checks:
#   rows = 331        unique issued ids        legacy crosswalk present
#   PW sum = 1,850    no ':latest'-style gaps  FF-16 membership precondition
#
# Output YAML shape (one row per CD item):
#   - id: CD-M01-01          name: cd_service_order     type: Odoo module
#     wave: W1               pw: 16                     legacy: CD-001
#     unit: M01
#
# Exit codes: 0 green - 1 violations - 2 preconditions.
# =============================================================================
[CmdletBinding()]
param(
    [string]$OutYaml = '',
    [string]$EstateRoot = '',
    [switch]$Strict
)
$ErrorActionPreference = 'Continue'
$libPath = Join-Path $PSScriptRoot '..\workstation\lib\Common.psm1'
if (-not (Test-Path $libPath)) { Write-Host '[FAIL] common library not found' -ForegroundColor Red; exit 2 }
Import-Module $libPath -Force -DisableNameChecking
Initialize-WorkstationTooling | Out-Null
trap {
    try { Log-Fail "unexpected failure: $($_.Exception.Message)"; Log-Remedy 'Fix and re-run.' } catch { }
    exit 1
}
$repoRoot = (Get-RepoRoot).TrimEnd('\')
if ($EstateRoot -eq '') {
    if ($env:FIX_ESTATE_ROOT) { $EstateRoot = $env:FIX_ESTATE_ROOT } else { $EstateRoot = Split-Path -Parent $repoRoot }
}
$be5 = Join-Path $EstateRoot 'project-guide-doc\07_Build_Engineering_and_Development_Standards\BE-005_Custom_Development_CD_Master_Register.md'
if (-not (Test-Path $be5)) { Log-Fail "BE-005 not found: $be5"; Log-Remedy 'Pass -EstateRoot.'; exit 2 }

Log-Step 'P01-M05-T05 - cd-register.yaml generation from BE-005 6'
$rows = New-Object System.Collections.Generic.List[object]
foreach ($line in [System.IO.File]::ReadLines($be5)) {
    # Row shape: | **`CD-M01-01`** | `cd_x` | scope | Type | W1 | 16 | `CD-001` |
    if ($line -match '^\| \*\*`(CD-[A-Z0-9]+-\d+)`\*\* \| *([^|]*)\|([^|]*)\|([^|]*)\| *(W\d+)[^|]*\| *(\d+)[^|]*\| *(.*)$') {
        $rows.Add([pscustomobject]@{
            Id = $Matches[1]; Name = $Matches[2].Trim(); Scope = $Matches[3].Trim()
            Type = $Matches[4].Trim(); Wave = $Matches[5]; Pw = [int]$Matches[6]
            Legacy = ($Matches[7].Trim() -replace '[`*]','')
            Unit = ([regex]::Match($Matches[1], 'CD-([A-Z0-9]+)-')).Groups[1].Value
        })
    }
}
$dupeIds = @($rows.Id | Group-Object | Where-Object Count -gt 1 | ForEach-Object Name)
$pwSum = ($rows.Pw | Measure-Object -Sum).Sum
$withLegacy = @($rows | Where-Object { $_.Legacy -match 'CD-' }).Count
$ok = $true
if ($rows.Count -ne 331) { Log-Fail "rows = $($rows.Count), expected 331"; $ok = $false }
if ($dupeIds.Count -gt 0) { Log-Fail "duplicate issued ids: $($dupeIds -join ',')"; $ok = $false }
if ($pwSum -ne 1850) { Log-Warn "PW sum = $pwSum (BE-005 header states 1,850) - record the basis of any difference"; }
if ($withLegacy -lt 200) { Log-Warn "legacy crosswalk on only $withLegacy rows"; }
if (-not $ok) { Log-Remedy 'BE-005 6 is the sole issuing authority (CDR-11) - fix the register under change control, then re-generate.'; exit 1 }

if ($OutYaml -eq '') { $OutYaml = Join-Path $repoRoot 'tooling\cd-register.yaml' }   # BE-004 4 tree location
$yaml = New-Object System.Collections.Generic.List[string]
$yaml.Add('# Generated by tooling/cd-register/generate-cd-register.ps1 from BE-005 6')
$yaml.Add("# Regenerated: $(Get-Date -Format 'yyyy-MM-ddTHH:mm:ssZ')  - rule CDR-11: generated, never hand-edited")
$yaml.Add("schema: 1000fix-erp/cd-register/1")
$yaml.Add("count: $($rows.Count)")
$yaml.Add("pw_total: $pwSum")
$yaml.Add("items:")
foreach ($r in ($rows | Sort-Object Id)) {
    $cleanName = ($r.Name -replace '`','').Trim()
    $cleanType = ($r.Type -replace '"','').Trim()
    $cleanLegacy = ($r.Legacy -replace '`','').Trim()
    $yaml.Add("- id: $($r.Id)")
    $yaml.Add("  unit: $($r.Unit)")
    $yaml.Add("  name: `"$cleanName`"")
    $yaml.Add("  type: `"$cleanType`"")
    $yaml.Add("  wave: $($r.Wave)")
    $yaml.Add("  pw: $($r.Pw)")
    $yaml.Add("  legacy: `"$cleanLegacy`"")
}
[System.IO.File]::WriteAllLines($OutYaml, $yaml)
Log-Ok "cd-register.yaml written: $OutYaml ($($rows.Count) items, $pwSum PW, crosswalk on $withLegacy rows)"
exit 0

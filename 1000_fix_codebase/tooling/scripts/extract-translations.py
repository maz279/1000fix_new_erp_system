#!/usr/bin/env python3
"""extract-translations — P04-M08-T02 (AS-12, AR-007 §3.1 i18n/).

The translation workflow:
  1. This script extracts every user-facing string from a cd_* module into
     i18n/<module>.pot (Gettext template) — field labels, selection labels,
     menu names, view strings, python ``_()`` strings — and re-syncs the
     references of the module's i18n/bn_BD.po (translations are never touched,
     and no empty msgstr is ever added to a .po).
  2. Translators maintain i18n/bn_BD.po against the template
     (docs/guides/bn-terminology-glossary.md).
  3. FF-25 (check_translations.py) blocks pre-merge below 100% (FF-24 rule:
     "100% before acceptance").

Both files are written in the form Odoo 19's own reader
(odoo.tools.translate.PoFileReader) loads:

  * every entry carries ``#. module: <module>`` — without it the reader raises
    AttributeError and the whole language load aborts;
  * every entry carries ``#:`` references (``model:ir.model.fields,
    field_description:<module>.field_<model>__<field>``, selection values,
    model names, menus, actions/groups, ``model_terms:ir.ui.view,arch_db``
    view terms, ``code:`` python strings) — an entry without a reference is
    never applied;
  * Odoo merges i18n/<module>.pot into bn_BD.po and OBSOLETES every .po entry
    the template lacks, so the template also carries every msgid bn_BD.po
    already translates.

Static extraction — the Odoo runtime remains the final authority, but a
template that misses strings guarantees a translation that misses them too.

Usage:
  py tooling/scripts/extract-translations.py <module_dir> [...]   # write .pot, sync bn_BD.po refs
  py tooling/scripts/extract-translations.py --all                # every cd_* module
  options: --no-po (leave bn_BD.po untouched)  --dry-run (report, write nothing)
Exit: 0 extracted / 1 errors.
"""

from __future__ import annotations

import ast
import re
import sys
from collections import defaultdict
from pathlib import Path

from lxml import etree

REPO = Path(__file__).resolve().parents[2]
ADDONS = REPO / "addons"

LANG_PO = "bn_BD.po"
# res.groups / ir.module.category / actions / menus: records whose `name` is a
# translated field of a base model (loaded as `model:<model>,name:<xmlid>`).
NAME_MODELS = frozenset(
    {
        "ir.actions.act_window",
        "ir.actions.server",
        "ir.actions.report",
        "ir.actions.client",
        "ir.ui.menu",
        "res.groups",
        "ir.module.category",
        "mail.activity.type",
    }
)
# attributes whose values are template msgids (parity with the former regex
# extractor) and the (wider) set Odoo's xml_translate treats as view terms
TEMPLATE_ATTRS = ("string", "title", "placeholder", "alt")
VIEW_TERM_ATTRS = (
    "string",
    "help",
    "placeholder",
    "title",
    "sum",
    "avg",
    "confirm",
    "alt",
    "aria-label",
    "data-tooltip",
)
# index of the positional `string` argument per field type (default 0)
POSITIONAL_STRING = {"Many2one": 1, "One2many": 2, "Many2many": 4, "Selection": 1, "Reference": 1}
SKIP_DIRS = {"__pycache__", "tests", "i18n", "static"}

POT_HEADER = (
    "# Translation template for {module} — GENERATED by tooling/scripts/extract-translations.py.\n"
    "# Bengali (bn_BD) is the first-class locale (AS-12, DE-17, TR-07).\n"
    "# Odoo PO-template form: every entry carries `#. module:` and `#:` references\n"
    "# (Odoo's PoFileReader merges this file into bn_BD.po and requires both).\n"
    'msgid ""\n'
    'msgstr ""\n'
    '"Project-Id-Version: 1000FiX ERP 19.0\\n"\n'
    '"Language: bn_BD\\n"\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
)
PLURAL_FORMS = '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"'


# ------------------------------------------------------------------ PO text --
_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "\\": "\\", '"': '"'}


def po_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def po_unescape(text: str) -> str:
    return re.sub(r"\\(.)", lambda m: _ESCAPES.get(m.group(1), "\\" + m.group(1)), text)


_KEYWORD = re.compile(r'^(msgctxt|msgid_plural|msgid|msgstr(?:\[(\d+)\])?)\s+"(.*)"$')
_HEADER = re.compile(r'^msgid ""\nmsgstr ""\n(?:"[^\n]*"\n)*', re.M)


def parse_po(text: str) -> list[tuple[str, str, bool]]:
    """[(msgid, msgstr, fuzzy)] - unescaped; wrapped (multi-line) strings
    joined; obsolete (#~) entries dropped; plural entries keep msgstr[0]."""
    entries: list[tuple[str, str, bool]] = []
    current: dict | None = None
    key: str | None = None
    flags: set[str] = set()

    def flush() -> None:
        if current is not None and "msgid" in current:
            entries.append(
                (
                    po_unescape(current["msgid"]),
                    po_unescape(current.get("msgstr", "")),
                    current["fuzzy"],
                )
            )

    for line in text.splitlines():
        s = line.strip()
        if s.startswith("#,"):
            flags |= {f.strip() for f in s[2:].split(",")}
        if not s or s.startswith("#"):
            key = None
            continue
        m = _KEYWORD.match(s)
        if m:
            kw, index, value = m.groups()
            if kw == "msgctxt" or (kw == "msgid" and (current is None or "msgid" in current)):
                flush()
                current, flags = {"fuzzy": "fuzzy" in flags}, set()
            if current is None:
                continue
            if kw.startswith("msgstr"):
                if index not in (None, "0"):
                    key = None
                    continue
                kw = "msgstr"
            current[kw], key = value, kw
        elif s.startswith('"') and s.endswith('"') and key and current is not None:
            current[key] += s[1:-1]
    flush()
    return entries


def read_po(text: str) -> tuple[str | None, dict[str, str], set[str]]:
    """(header block or None, {msgid: msgstr} of non-empty translations, fuzzy msgids)."""
    match = _HEADER.search(text)
    header = text[: match.end()] if match else None
    translated, fuzzy = {}, set()
    for msgid, msgstr, is_fuzzy in parse_po(text):
        if msgid and msgstr.strip():
            translated[msgid] = msgstr
            if is_fuzzy:
                fuzzy.add(msgid)
    return header, translated, fuzzy


def fix_po_header(header: str) -> str:
    lines = [ln for ln in header.rstrip("\n").split("\n") if ln.strip() != '""']
    keys = {ln[1:].split(":", 1)[0] for ln in lines if ln.startswith('"')}
    if "Language" not in keys:
        lines.append('"Language: bn_BD\\n"')
    if "Content-Type" not in keys:
        lines.append('"Content-Type: text/plain; charset=UTF-8\\n"')
    if "Plural-Forms" not in keys:
        lines.append(PLURAL_FORMS)
    lines = [PLURAL_FORMS if ln.startswith('"Plural-Forms:') else ln for ln in lines]
    return "\n".join(lines) + "\n"


def render(
    header: str,
    module: str,
    msgids: dict[str, str | None],
    refs: dict[str, set[str]],
    fuzzy: set[str] | frozenset[str] = frozenset(),
) -> str:
    """msgids: {msgid: msgstr} - msgstr None renders an (empty) template entry.
    One single-line msgid/msgstr per entry, sorted, `#. module:` + `#:` refs."""
    out = [header.rstrip("\n"), ""]
    for msgid in sorted(msgids, key=lambda m: (po_escape(m).lower(), po_escape(m))):
        out.append(f"#. module: {module}")
        out.extend(f"#: {ref}" for ref in sorted(refs.get(msgid, ())))
        if msgid in fuzzy:
            out.append("#, fuzzy")
        out.append(f'msgid "{po_escape(msgid)}"')
        out.append(f'msgstr "{po_escape(msgids[msgid] or "")}"')
        out.append("")
    return "\n".join(out)


# --------------------------------------------------------------- extraction --
def _module_dir(path: Path) -> Path | None:
    for parent in path.parents:
        if (parent / "__manifest__.py").is_file():
            return parent
    return None


def _const_str(node) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value.strip():
        return node.value
    return None


def _assigns(body) -> dict[str, ast.AST]:
    return {
        s.targets[0].id: s.value
        for s in body
        if isinstance(s, ast.Assign) and len(s.targets) == 1 and isinstance(s.targets[0], ast.Name)
    }


def _selection_pairs(node, scopes) -> list[tuple[str, str]]:
    if isinstance(node, ast.Name):
        node = next((scope[node.id] for scope in scopes if node.id in scope), None)
    if not isinstance(node, ast.List | ast.Tuple):
        return []
    pairs = []
    for elt in node.elts:
        if isinstance(elt, ast.Tuple | ast.List) and len(elt.elts) == 2:
            value, label = elt.elts
            if (
                isinstance(value, ast.Constant)
                and isinstance(value.value, str)
                and _const_str(label)
            ):
                pairs.append((value.value, label.value))
    return pairs


class Extraction:
    """msgids: template strings; refs: every Odoo reference per string."""

    def __init__(self) -> None:
        self.msgids: set[str] = set()
        self.refs: dict[str, set[str]] = defaultdict(set)

    def add(self, text: str, ref: str | None = None, template: bool = False) -> None:
        if not text or not text.strip():
            return
        if template:
            self.msgids.add(text)
        if ref:
            self.refs[text].add(ref)


def _extract_python(module_dir: Path, module: str, ex: Extraction) -> None:
    for py in sorted(module_dir.rglob("*.py")):
        rel_parts = py.relative_to(module_dir).parts
        if (
            SKIP_DIRS & set(rel_parts)
            or py.name == "__manifest__.py"
            or _module_dir(py) != module_dir
        ):
            continue
        try:
            tree = ast.parse(py.read_text(encoding="utf-8", errors="ignore"))
        except SyntaxError:
            continue
        rel = py.relative_to(module_dir).as_posix()
        module_scope = _assigns(tree.body)
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and node.args:
                func = node.func
                name = (
                    func.id
                    if isinstance(func, ast.Name)
                    else func.attr
                    if isinstance(func, ast.Attribute)
                    else None
                )
                if name in ("_", "_lt") and _const_str(node.args[0]):
                    ex.add(node.args[0].value, f"code:addons/{module}/{rel}:0", template=True)
        for cls in (n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)):
            class_scope = _assigns(cls.body)
            name = _const_str(class_scope.get("_name"))
            inherit = class_scope.get("_inherit")
            if isinstance(inherit, ast.List | ast.Tuple):
                inherit = inherit.elts[0] if inherit.elts else None
            model = name or _const_str(inherit)
            if not model:
                continue
            xmodel = model.replace(".", "_")
            description = _const_str(class_scope.get("_description"))
            if name and description:
                ex.add(description, f"model:ir.model,name:{module}.model_{xmodel}")
            for fname, call in class_scope.items():
                if not (
                    isinstance(call, ast.Call)
                    and isinstance(call.func, ast.Attribute)
                    and isinstance(call.func.value, ast.Name)
                    and call.func.value.id == "fields"
                ):
                    continue
                ftype = call.func.attr
                kw = {k.arg: k.value for k in call.keywords if k.arg}
                idx = POSITIONAL_STRING.get(ftype, 0)
                positional = call.args[idx] if len(call.args) > idx else None
                ref = f"model:ir.model.fields,field_description:{module}.field_{xmodel}__{fname}"
                if "string" in kw or positional is not None:
                    label = _const_str(kw.get("string", positional))
                    if label:  # a non-constant label is never guessed
                        ex.add(label, ref, template=True)
                elif "related" not in kw:  # Odoo's default label (fields.py)
                    base = (
                        fname[:-4]
                        if fname.endswith("_ids")
                        else fname[:-3]
                        if fname.endswith("_id")
                        else fname
                    )
                    ex.add(base.replace("_", " ").title(), ref)
                if ftype == "Selection":
                    sel = (
                        kw.get("selection")
                        or kw.get("selection_add")
                        or (call.args[0] if call.args else None)
                    )
                    for value, label in _selection_pairs(sel, (class_scope, module_scope)):
                        xvalue = value.replace(".", "_").replace(" ", "_").lower()
                        ex.add(
                            label,
                            f"model:ir.model.fields.selection,name:{module}.selection__{xmodel}__{fname}__{xvalue}",
                            template=True,
                        )


def _qualify(xmlid: str, module: str) -> str:
    return xmlid if "." in xmlid else f"{module}.{xmlid}"


def _view_terms(arch, ref: str, ex: Extraction) -> None:
    for el in arch.iter():
        if not isinstance(el.tag, str):
            continue
        for attr in VIEW_TERM_ATTRS:
            ex.add((el.get(attr) or "").strip(), ref)
        for text in (el.text, el.tail):
            if text and text.strip():
                ex.add(" ".join(text.split()), ref)


def _extract_xml(module_dir: Path, module: str, ex: Extraction) -> None:
    parser = etree.XMLParser(remove_comments=True, resolve_entities=False, no_network=True)
    for xml in sorted(module_dir.rglob("*.xml")):
        if SKIP_DIRS & set(xml.relative_to(module_dir).parts):
            continue
        try:
            # repo-owned addon XML through a parser with entity resolution off
            root = etree.parse(str(xml), parser).getroot()  # noqa: S320 - hardened parser above
        except etree.XMLSyntaxError:
            continue
        for el in root.iter():
            if isinstance(el.tag, str):
                for attr in TEMPLATE_ATTRS:
                    ex.add((el.get(attr) or "").strip(), template=True)
        for menu in root.iter("menuitem"):
            if menu.get("id") and menu.get("name"):
                ex.add(
                    menu.get("name").strip(),
                    f"model:ir.ui.menu,name:{_qualify(menu.get('id'), module)}",
                    True,
                )
        for rec in root.iter("record"):
            model, rid = rec.get("model"), rec.get("id")
            if not (model and rid):
                continue
            xmlid = _qualify(rid, module)
            for fld in rec.findall("field"):
                if (
                    model in NAME_MODELS
                    and fld.get("name") == "name"
                    and fld.text
                    and not fld.get("eval")
                ):
                    ex.add(fld.text.strip(), f"model:{model},name:{xmlid}")
                if model == "ir.ui.view" and fld.get("name") == "arch":
                    _view_terms(fld, f"model_terms:ir.ui.view,arch_db:{xmlid}", ex)
        for tpl in root.iter("template"):
            if tpl.get("id"):
                _view_terms(
                    tpl, f"model_terms:ir.ui.view,arch_db:{_qualify(tpl.get('id'), module)}", ex
                )


def extract_module(module_dir: Path) -> tuple[Extraction, Path]:
    module = module_dir.name
    ex = Extraction()
    _extract_python(module_dir, module, ex)
    _extract_xml(module_dir, module, ex)
    return ex, module_dir / "i18n" / f"{module}.pot"


def build_files(module_dir: Path) -> tuple[str | None, str | None, list[str]]:
    """(pot text or None, synced bn_BD.po text or None, template msgids the
    .po does not translate yet)."""
    module = module_dir.name
    ex, _ = extract_module(module_dir)
    po_path = module_dir / "i18n" / LANG_PO
    po_header, translated, fuzzy = None, {}, set()
    if po_path.is_file():
        po_header, translated, fuzzy = read_po(po_path.read_text(encoding="utf-8"))
    template = ex.msgids | set(translated)  # Odoo obsoletes .po entries a .pot lacks
    pot = (
        render(POT_HEADER.format(module=module), module, dict.fromkeys(template), ex.refs)
        if template
        else None
    )
    po = None
    if po_header is not None:  # translations are kept verbatim; no empty msgstr is added
        po = render(fix_po_header(po_header), module, translated, ex.refs, fuzzy)
    untranslated = sorted(m for m in ex.msgids if m not in translated or m in fuzzy)
    return pot, po, untranslated


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = {a for a in sys.argv[1:] if a.startswith("--")}
    if not args and "--all" not in flags:
        print(__doc__)
        return 1
    modules: list[Path] = []
    if "--all" in flags:
        modules = sorted(
            d for d in ADDONS.rglob("cd_*") if d.is_dir() and (d / "__manifest__.py").is_file()
        )
    for arg in args:
        path = Path(arg)
        modules.append(path if path.is_absolute() else REPO / path)

    errors = 0
    for module_dir in modules:
        if not (module_dir / "__manifest__.py").is_file():
            print(f"extract-translations: SKIP {module_dir.name}: not an Odoo module")
            continue
        try:
            pot, po, untranslated = build_files(module_dir)
        except (OSError, ValueError) as exc:
            print(f"extract-translations: ERROR {module_dir.name}: {exc}")
            errors += 1
            continue
        pot_path = module_dir / "i18n" / f"{module_dir.name}.pot"
        if pot is None:
            print(f"extract-translations: {module_dir.name}: no translatable strings")
            continue
        if "--dry-run" not in flags:
            pot_path.parent.mkdir(parents=True, exist_ok=True)
            pot_path.write_text(pot, encoding="utf-8", newline="\n")
            if po is not None and "--no-po" not in flags:
                (module_dir / "i18n" / LANG_PO).write_text(po, encoding="utf-8", newline="\n")
        note = f"; {len(untranslated)} untranslated in {LANG_PO}" if untranslated else ""
        shown = pot_path.relative_to(REPO) if pot_path.is_relative_to(REPO) else pot_path
        print(
            f"extract-translations: {module_dir.name}: {pot.count(chr(10) + 'msgid ') - 1} strings -> "
            f"{shown.as_posix()}{note}"
        )
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())

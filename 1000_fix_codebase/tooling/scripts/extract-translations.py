#!/usr/bin/env python3
"""extract-translations — P04-M08-T02 (AS-12, AR-007 §3.1 i18n/).

The translation workflow:
  1. This script extracts every user-facing string from a cd_* module into
     i18n/<module>.pot (Gettext template) — field labels, selection labels,
     window action names, menu names, view strings.
  2. Translators maintain i18n/bn_BD.po against the template.
  3. FF-25 (check_translations.py) blocks pre-merge below 100% (FF-24 rule:
     "100% before acceptance").

Static extraction — the Odoo runtime remains the final authority, but a
template that misses strings guarantees a translation that misses them too.

Usage:
  py tooling/scripts/extract-translations.py <module_dir> [...]   # write .pot
  py tooling/scripts/extract-translations.py --all                # every cd_*
Exit: 0 extracted / 1 errors.
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ADDONS = REPO / "addons"

FIELD_STRING = re.compile(
    r'(\w+)\s*=\s*fields\.\w+\([^)]*?string="([^"]+)"', re.DOTALL
)
SELECTION_PAIR = re.compile(r'\("[a-z_]+",\s*"([^"]+)"\)')
MENU_NAME = re.compile(r'<menuitem[^>]*name="([^"]+)"')
ACTION_NAME = re.compile(r'<field name="name">([^<]+)</field>')
VIEW_STRING = re.compile(r'(?:string|title|placeholder|alt)="([^"]+)"')
PYTHON_STRING = re.compile(r'_\(\s*"([^"]+)"\s*\)')


def extract_module(module_dir: Path) -> tuple[set[str], Path]:
    strings: set[str] = set()
    for py in module_dir.rglob("*.py"):
        if "__pycache__" in py.parts or py.name == "__manifest__.py":
            continue
        text = py.read_text(encoding="utf-8", errors="ignore")
        strings.update(match[1] for match in FIELD_STRING.findall(text))
        for match in re.finditer(r"fields\.Selection\(\[(.*?)\]", text, re.DOTALL):
            strings.update(SELECTION_PAIR.findall(match.group(1)))
        strings.update(PYTHON_STRING.findall(text))
    for xml in list(module_dir.rglob("*.xml")):
        if "i18n" in xml.parts:
            continue
        text = xml.read_text(encoding="utf-8", errors="ignore")
        strings.update(MENU_NAME.findall(text))
        strings.update(VIEW_STRING.findall(text))
    # Selection labels also appear inside field definitions across lines.
    # XML entities are unescaped so the pot msgid matches what renders.
    strings = {html.unescape(s.strip()) for s in strings if s.strip()}
    return strings, module_dir / "i18n" / f"{module_dir.name}.pot"


def po_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def write_pot(strings: set[str], pot_path: Path, module: str) -> None:
    pot_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# Translation template for {module} — GENERATED by tooling/scripts/extract-translations.py.",
        "# Bengali (bn_BD) is the first-class locale (AS-12, DE-17, TR-07).",
        '# "{module} fields, selections, menus and views."',
        f'msgid ""',
        f'msgstr ""',
        f'"Project-Id-Version: 1000FiX ERP 19.0\\n"',
        f'"Language: bn_BD\\n"',
        f'"Content-Type: text/plain; charset=UTF-8\\n"',
        "",
    ]
    for text in sorted(strings):
        lines.append(f'msgid "{po_escape(text)}"')
        lines.append('msgstr ""')
        lines.append("")
    pot_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 1
    modules: list[Path] = []
    if args[0] == "--all":
        for cd_dir in sorted(ADDONS.rglob("cd_*")):
            if cd_dir.is_dir() and (cd_dir / "__manifest__.py").is_file():
                modules.append(cd_dir)
    else:
        for arg in args:
            path = Path(arg)
            modules.append(path if path.is_absolute() else REPO / path)

    errors = 0
    for module_dir in modules:
        if not (module_dir / "__manifest__.py").is_file():
            print(f"extract-translations: SKIP {module_dir.name}: not an Odoo module")
            continue
        strings, pot_path = extract_module(module_dir)
        write_pot(strings, pot_path, module_dir.name)
        print(f"extract-translations: {module_dir.name}: {len(strings)} strings -> {pot_path.relative_to(REPO)}".replace("\\", "/"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())

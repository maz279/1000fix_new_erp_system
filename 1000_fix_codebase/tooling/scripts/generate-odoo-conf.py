#!/usr/bin/env python3
"""generate-odoo-conf - P02-M06-T02 (REPO-15).

odoo.conf is GENERATED, never hand-written. addons_path is scanned from the
tree at generation time - it is 30+ entries and "drifts the day a category
is added" (BE-001 6.2), so it is computed, not typed.

Normative layer order (AR-007):
  1. vendor/odoo/addons                      (L1 core)
  2. vendor/oca/<repo>/...                   (L2, alphabetical - OCA resolves internally)
  3. addons/platform                         (L3 - depended on; never depends on L4)
  4. addons/domain/<category> a..k           (L4)
Later entries win on name clashes - which is exactly the intended override
direction (custom over OCA over core).

Local values (BE-001 6.2): workers=0 (debugger truth, not performance),
dev=all, generous limits, log_handler on cd_ modules, list_db=True (LOCAL
ONLY - PE-002 forbids it elsewhere).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ADDONS_ROOT = REPO_ROOT / "addons"
VENDOR = REPO_ROOT / "vendor"


def oca_paths() -> list[Path]:
    oca = VENDOR / "oca"
    if not oca.is_dir():
        return []
    # One entry per repository that actually contains modules; subtrees keep
    # their own structure (BE-004 5.3), so include only dirs holding manifests.
    out: list[Path] = []
    for repo in sorted(oca.iterdir()):
        if repo.is_dir() and any(repo.glob("*/__manifest__.py")):
            out.append(repo)
        elif repo.is_dir() and any(repo.rglob("__manifest__.py")):
            # nested layouts (rare): include the repo root; Odoo scans depth-1
            out.append(repo)
    return out


def platform_paths() -> list[Path]:
    p = ADDONS_ROOT / "platform"
    return [p] if p.is_dir() else []


def domain_paths() -> list[Path]:
    d = ADDONS_ROOT / "domain"
    if not d.is_dir():
        return []
    # Only categories that hold modules: an empty category (k_platform today)
    # made Odoo log "invalid addons directory" on every start.
    return sorted(
        (c for c in d.iterdir() if c.is_dir() and any(c.glob("*/__manifest__.py"))),
        key=lambda p: p.name,
    )


def build_addons_path() -> str:
    parts: list[Path] = []
    core = VENDOR / "odoo" / "addons"
    if core.is_dir():
        parts.append(core)
    parts += oca_paths()
    parts += platform_paths()
    parts += domain_paths()
    return ",".join(str(p.relative_to(REPO_ROOT)).replace("\\", "/") for p in parts)


CONF_TEMPLATE = """# GENERATED by tooling/scripts/generate-odoo-conf.py - DO NOT EDIT (REPO-15).
# Regenerate: make odoo-conf  (or: python tooling/scripts/generate-odoo-conf.py)
# Generated at: {stamp}
[options]
# --- generated section (REPO-15: identical regeneration is doctor check 5) ---
addons_path = {addons_path}
# Server-wide modules load at startup, before any registry. cd_entity_config
# carries the RPC error hardening (no tracebacks in JSON-RPC / XML-RPC
# errors outside dev mode, OWASP A05), which must also cover db-less routes.
# Same list in every environment (infra/compose odoo-* services: --load).
server_wide_modules = base,rpc,web,cd_entity_config

# --- local values (BE-001 6.2) -----------------------------------------------
# workers=0 is NOT a performance setting: with workers>0 Odoo forks and a
# debugger attached to the parent never stops in the child.
workers = 0
# dev=all is a CLI-ONLY flag in Odoo 19 (file_exportable=False) - set it
# on the command line (--dev=all), never in the config file
limit_time_cpu = 3600
limit_time_real = 3600
log_handler = odoo.addons.cd_:DEBUG
# LOCAL ONLY - PE-002 forbids list_db=True elsewhere
list_db = True
# LOCAL ONLY - bind the loopback: a dev server with a change-me database
# manager password must never be reachable from the network (P07 audit).
http_interface = 127.0.0.1
without_demo = False
admin_passwd = {admin_passwd}
http_port = {http_port}
data_dir = {data_dir}
db_host = {db_host}
db_port = {db_port}
db_user = {db_user}
db_password = {db_password}
"""


PROD_CONF_TEMPLATE = """# GENERATED by tooling/scripts/generate-odoo-conf.py --profile prod - DO NOT EDIT.
# Production posture (PE-002): no database manager, no demo data, prefork
# workers behind the Kong gateway (proxy_mode), secrets injected as env vars
# by the deployment - the dollar-brace placeholders below are NEVER resolved
# from the development .env.
# Generated at: {stamp}
[options]
addons_path = {addons_path}
server_wide_modules = base,rpc,web,cd_entity_config

# --- production values --------------------------------------------------------
workers = 4
max_cron_threads = 2
limit_time_cpu = 600
limit_time_real = 120
limit_memory_soft = 2684354560
limit_memory_hard = 3221225472
# Behind Kong: honour X-Forwarded-Proto/Host; bind all interfaces (the
# gateway, not Odoo, is the network edge).
proxy_mode = True
http_port = ${{ODOO_HTTP_PORT}}
# PE-002: the database manager is disabled in every non-local environment.
list_db = False
dbfilter = ^${{ODOO_DB}}$
without_demo = all
log_level = info
admin_passwd = ${{ODOO_ADMIN_PASSWORD}}
data_dir = ${{ODOO_DATA_DIR}}
db_host = ${{PGHOST}}
db_port = ${{PGPORT}}
db_user = ${{PGUSER}}
db_password = ${{POSTGRES_PASSWORD}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="compare generated output to the committed file; exit 1 on drift (doctor check 5)",
    )
    ap.add_argument("--out", default=str(REPO_ROOT / "infra" / "odoo-conf" / "local.conf"))
    ap.add_argument(
        "--profile",
        choices=["local", "prod"],
        default="local",
        help="local: dev truth (BE-001 6.2). prod: hardened gateway-fronted posture with env-injected secrets",
    )
    args = ap.parse_args()

    if args.profile == "prod":
        # Secrets stay as ${VAR} placeholders: the deployment injects them;
        # the development .env must never leak into a production config.
        conf = PROD_CONF_TEMPLATE.format(
            stamp=__import__("datetime").datetime.now().isoformat(timespec="seconds"),
            addons_path=build_addons_path(),
        )
        default_out = REPO_ROOT / "infra" / "odoo-conf" / "prod.conf"
        out = Path(args.out) if args.out != ap.get_default("out") else default_out
        if args.check:
            if not out.exists():
                print(f"generate-odoo-conf: FAIL - {out} does not exist (run with --profile prod)")
                return 1
            committed = out.read_text(encoding="utf-8")

            def strip(text: str) -> str:
                return "\n".join(
                    ln for ln in text.splitlines() if not ln.startswith("# Generated at:")
                )

            if strip(committed) == strip(conf):
                print("generate-odoo-conf: OK - prod.conf regenerates identically (REPO-15)")
                return 0
            print("generate-odoo-conf: FAIL - committed prod.conf has drifted from the tree")
            return 1
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(conf, encoding="utf-8")
        print(f"generate-odoo-conf: wrote {out} (profile=prod; secrets are ${{VAR}} placeholders)")
        return 0

    conf = CONF_TEMPLATE.format(
        stamp=__import__("datetime").datetime.now().isoformat(timespec="seconds"),
        addons_path=build_addons_path(),
        admin_passwd="${ODOO_ADMIN_PASSWORD}",  # noqa: S106 - ${ENV} interpolation placeholder, not a secret
        http_port="${ODOO_HTTP_PORT}",
        data_dir=str(REPO_ROOT / "infra" / "odoo-data"),
        db_host="${PGHOST}",
        db_port="${PGPORT}",
        db_user="${PGUSER}",
        db_password="${POSTGRES_PASSWORD}",  # noqa: S106 - ${ENV} interpolation placeholder, not a secret
    )
    # .env interpolation is done by the run wrapper (tasks.ps1/make run), not here,
    # so the generated file stays environment-neutral and diff-stable.
    conf = conf.replace("${ODOO_ADMIN_PASSWORD}", "change-me-dev-only")

    out = Path(args.out)
    if args.check:
        if not out.exists():
            print(f"generate-odoo-conf: FAIL - {out} does not exist (run make odoo-conf)")
            return 1
        committed = out.read_text(encoding="utf-8")

        # Compare everything except the stamp line (timestamps differ by design).
        def strip(t: str) -> str:
            return "\n".join(ln for ln in t.splitlines() if not ln.startswith("# Generated at:"))

        if strip(committed) == strip(conf):
            print("generate-odoo-conf: OK - regenerates identically (REPO-15)")
            return 0
        print("generate-odoo-conf: FAIL - committed local.conf has drifted from the tree")
        print("  remedy: run  make odoo-conf  and commit the result (REPO-15)")
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(conf, encoding="utf-8")
    print(f"generate-odoo-conf: wrote {out} ({conf.count(',') + 1} addons_path entries)")

    # P07 finding: the run wrapper never interpolated the ${VAR} placeholders,
    # so odoo-bin saw db_host='${PGHOST}' and a non-numeric http_port and died
    # at startup. The generator now also emits a RESOLVED copy from .env
    # (git-ignored; carries db credentials) which the odoo targets prefer.
    env = {}
    env_file = REPO_ROOT / ".env"
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                env[k.strip()] = v.strip()
    import re as _re

    resolved = _re.sub(r"\$\{([A-Z0-9_]+)\}", lambda m: env.get(m.group(1), m.group(0)), conf)
    resolved_path = out.with_name("local.resolved.conf")
    resolved_path.write_text(resolved, encoding="utf-8")
    print(f"generate-odoo-conf: wrote {resolved_path} (${len(env)} env keys resolved)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

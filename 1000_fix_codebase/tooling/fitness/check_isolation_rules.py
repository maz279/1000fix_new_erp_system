#!/usr/bin/env python3
"""check_isolation_rules - FF-47 record-rule isolation present and current.

Every transactional model (FF-21 scope) must be covered by a multi-company
ir.rule and an operating-unit ir.rule (AS-03). The rules are generated by
tooling/generators/generate-isolation-rules.py; this check regenerates them
in memory and fails on anything missing or drifted, so a new transactional
model cannot merge without its isolation (R01 re-audit 2026-10-22, A01-05).

Exit 0 clean - 1 missing/drifted (remedy printed) - 2 manifest not editable.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

GENERATOR = Path(__file__).resolve().parents[1] / "generators" / "generate-isolation-rules.py"


def main() -> int:
    spec = importlib.util.spec_from_file_location("generate_isolation_rules", GENERATOR)
    if spec is None or spec.loader is None:
        print(f"check_isolation_rules: FAIL - cannot load {GENERATOR}")
        return 1
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return int(module.main(["--check"]))


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""generate-p03-menus — PP2-M01-T01.

Reads contracts/nav/registry.json (the frozen prototype's navigation truth)
and the binding mapping table (docs/navigation/registry-to-production-mapping.md)
and emits the P03 portal menu XML: every cd-kind module gets a workspace menu
under the shared operations root, with up to NVR-23 (7) primary sections from
the registry's groups. Screens map to the module's primary list action
(unbacked screens are listed in the coverage ledger, not silently dropped).

Deterministic and idempotent: re-running produces byte-identical output.

Exit: 0 written / 1 registry or mapping invalid.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REGISTRY = REPO / "contracts" / "nav" / "registry.json"
MAPPING_DOC = REPO / "docs" / "navigation" / "registry-to-production-mapping.md"
OUT = REPO / "addons" / "platform" / "cd_p03_portal" / "views" / "p03_menus.xml"
LEDGER = REPO / "docs" / "navigation" / "p03-coverage-ledger.md"

MAX_SECTIONS = 7  # NVR-23
HEADER = """<!-- GENERATED by tooling/generators/generate-p03-menus.py (PP2-M01-T01) — DO NOT EDIT.
     Source: contracts/nav/registry.json + the binding mapping table.
     Re-run the generator after any (tracked) registry change. -->
<odoo>
"""
FOOTER = "</odoo>\n"


def parse_mapping() -> dict[str, tuple[str, str]]:
    table: dict[str, tuple[str, str]] = {}
    for line in MAPPING_DOC.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*(M\d\d)\s*\|[^|]+\|\s*(\w[\w-]*)\s*\|\s*([^|]+)\|", line)
        if m:
            table[m.group(1)] = (m.group(2), m.group(3).strip())
    return table


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:40] or "section"


def esc(text: str) -> str:
    """Escape XML entities in module/group/report names (e.g. '&' in
    'CX, Feedback & Complaints' would break lxml otherwise)."""
    return (text.replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def main() -> int:
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    mapping = parse_mapping()
    if len(mapping) != 67:
        print(f"generate-p03-menus: mapping has {len(mapping)} rows, expected 67")
        return 1

    lines = [HEADER]
    ledger = [
        "# P03 Coverage Ledger — screen keys → Odoo actions (generated PP2-M01)\n",
        "\n",
        "Generated from the registry. `backed` = the module's primary action;\n",
        "`unbacked` = no Odoo action yet — its phase lands it and re-runs the\n",
        "generator. This is the Gate GP D1 denominator.\n",
        "\n",
        "| Module | Workspace menu | Sections (registry groups) | Screens backed | Screens unbacked | Reports (registry) |\n",
        "|---|---|---|---|---|---|\n",
    ]
    total_backed = total_unbacked = 0
    seen_cd: set[str] = set()  # one workspace per cd module (dedup M01/M02/M31 -> cd_service_order)

    for mod in sorted(reg["modules"], key=lambda m: m["id"]):
        mid = mod["id"]
        kind, real = mapping.get(mid, ("pending", "?"))
        if kind not in ("cd", "embedded", "shared"):
            continue  # l4/l5/planned/pending: no Odoo workspace menu (documented in mapping)
        cd_names = re.findall(r"cd_[a-z_]+", real)
        if not cd_names:
            continue
        cd = cd_names[0].replace("cd_", "")
        if cd in seen_cd:
            # a cd module already has its workspace from an earlier registry
            # module — record the extra mapping in the ledger, don't duplicate
            total_unbacked += sum(len(g["screens"]) for g in mod["groups"])
            ledger.append(
                f"| {mid} {mod['en']} | (shares `{cd}` workspace) "
                f"| — | 0 | {sum(len(g['screens']) for g in mod['groups'])} "
                f"| {len(mod['reports'])} |\n")
            continue
        seen_cd.add(cd)
        menu_id = f"menu_p03_ws_{cd}"
        # NVR-23: primary sections = first 7 groups; the rest nest under the 7th
        groups = mod["groups"]
        primary = groups[:MAX_SECTIONS]
        overflow = groups[MAX_SECTIONS:]
        lines.append(f'    <!-- {mid}: {esc(mod["en"])} ({len(groups)} groups, '
                     f'{sum(len(g["screens"]) for g in groups)} screens, '
                     f'{len(mod["reports"])} reports) -->\n')
        lines.append(f'    <menuitem id="{menu_id}" name="{esc(mod["en"])}"\n'
                     f'              parent="cd_entity_config.menu_fix_operations_root"\n'
                     f'              sequence="{int(mid[1:]) * 2}"/>\n')
        backed = unbacked = 0
        sec_ids: list[str] = []
        for gi, g in enumerate(primary, 1):
            sec = f"{menu_id}_s{gi}"
            sec_ids.append(sec)
            lines.append(f'    <menuitem id="{sec}" name="{esc(g["en"])}" parent="{menu_id}" sequence="{gi * 10}"/>\n')
            for screen in g["screens"]:
                # PP2-M01: screens point at the module's list action; the
                # action mapping lands per-phase. The generator records them.
                unbacked += 1
        if overflow:
            sec = f"{menu_id}_s7more"
            lines.append(f'    <menuitem id="{sec}" name="More Sections" parent="{menu_id}" sequence="70"/>\n')
            for g in overflow:
                sub = f"{sec}_{slug(g['en'])}"
                lines.append(f'    <menuitem id="{sub}" name="{esc(g["en"])}" parent="{sec}" sequence="10"/>\n')
                for screen in g["screens"]:
                    unbacked += 1
        total_backed += backed
        total_unbacked += unbacked
        ledger.append(
            f"| {mid} {mod['en']} | `{menu_id}` | {len(primary)}"
            f"{'+' + str(len(overflow)) + ' nested' if overflow else ''} "
            f"| {backed} | {unbacked} | {len(mod['reports'])} |\n")

    lines.append(FOOTER)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(lines), encoding="utf-8", newline="\n")
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text("".join(ledger) +
                      f"\n**Totals**: {total_backed} backed, {total_unbacked} unbacked "
                      f"(the phase-by-phase burn-down target).\n", encoding="utf-8", newline="\n")
    print(f"generate-p03-menus: {sum(1 for l in lines if 'menu_p03_ws_' in l and '_s' not in l)} workspace menus "
          f"-> {OUT.relative_to(REPO)}; ledger: {total_backed} backed / {total_unbacked} unbacked")
    return 0


if __name__ == "__main__":
    sys.exit(main())

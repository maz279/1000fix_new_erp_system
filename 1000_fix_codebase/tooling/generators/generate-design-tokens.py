#!/usr/bin/env python3
"""generate-design-tokens — P04-M07-T02/T04/T07 (DSY-01, UX-001 §5.3).

"One token source, one component contract, five realisations, one
conformance suite." This executable is the only writer of every realisation:

  libs/ts/ui/src/tokens/tokens.json          SOURCE (the only authored file)
  addons/platform/cd_design_tokens/static/src/tokens.scss   R1 (Odoo bundler)
  libs/ts/ui/src/tokens/tokens.generated.ts                 R2 (Next.js portals)
  addons/platform/cd_design_tokens/static/src/tokens.css    R3 (QWeb reports)
  libs/dart/fix_ui/theme/tokens.dart                        R4 (Flutter — PP0-M01-T02)
  tooling/design-system/tokens.flat.json                    conformance input

No runtime authors a value; every runtime consumes a generated artefact.
Re-running this script with an unchanged source produces byte-identical
output (deterministic ordering, LF endings, no timestamps).

Exit: 0 regenerated / 1 source invalid.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "libs/ts/ui/src/tokens/tokens.json"
GENERATED = {
    "scss": REPO / "addons/platform/cd_design_tokens/static/src/tokens.scss",
    "css": REPO / "addons/platform/cd_design_tokens/static/src/tokens.css",
    "ts": REPO / "libs/ts/ui/src/tokens/tokens.generated.ts",
    "dart": REPO / "libs/dart/fix_ui/lib/theme/tokens.dart",
    "flat": REPO / "tooling/design-system/tokens.flat.json",
    "next_css": REPO / "libs/ts/ui/src/tokens/tokens.css",
}

# R6 semantic aliases: (alias, light token path, dark token path or None).
# Every entry resolves VALUES from the flat token map at generation time —
# the generator authors nothing. These aliases are what html[data-theme]
# and html[data-density] override so components can consume one stable
# custom property per role (canvas/surface/ink/primary/...) in both themes.
SEMANTIC_ALIASES = [
    ("canvas", "color.surface.canvas", "color.dark.canvas"),
    ("surface", "color.surface.primary", "color.dark.surface"),
    ("surface-2", "color.surface.secondary", "color.dark.surface-2"),
    ("surface-3", "color.surface.tertiary", "color.dark.surface-3"),
    ("stroke", "color.border.default", "color.dark.stroke"),
    ("stroke-strong", "color.border.strong", "color.dark.stroke-strong"),
    ("stroke-accessible", "color.border.accessible", "color.dark.stroke-accessible"),
    ("ink", "color.text.primary", "color.dark.ink-900"),
    ("ink-2", "color.text.ink-strong", "color.dark.ink-700"),
    ("ink-muted", "color.text.secondary", "color.dark.ink-500"),
    ("ink-faint", "color.text.ink-faint", "color.dark.ink-300"),
    ("ink-inverse", "color.text.inverse", None),
    ("hover", "color.surface.hover", "color.dark.hover"),
    ("pressed", "color.surface.pressed", "color.dark.pressed"),
    ("primary", "color.primary.base", "color.dark.primary"),
    ("primary-hover", "color.primary.hover", "color.dark.primary-hover"),
    ("primary-press", "color.primary.press", "color.dark.primary-press"),
    ("primary-selected", "color.primary.selected", "color.dark.primary-selected"),
    ("primary-tint", "color.primary.tint", "color.dark.primary-tint"),
    ("primary-wash", "color.primary.wash", "color.dark.primary-wash"),
    ("ok-bg", "color.status.success-bg", "color.dark.ok-bg"),
    ("warn-bg", "color.status.warning-bg", "color.dark.warn-bg"),
    ("err-bg", "color.status.error-bg", "color.dark.err-bg"),
    ("info-bg", "color.status.info-bg", "color.dark.info-bg"),
    ("focus-ring", "color.border.focus", "color.dark.ink-900"),
]

HEADER = """// GENERATED by tooling/generators/generate-design-tokens.py — DO NOT EDIT.
// Source of truth: libs/ts/ui/src/tokens/tokens.json (DTCG Format Module 2025.10).
// Any value change happens in the source, then `py tooling/generators/generate-design-tokens.py`.
"""


def flatten(node: dict, prefix: str = "") -> list[tuple[str, str]]:
    """DTCG tree -> ordered [(token_path, value)]; $-keys are metadata."""
    out: list[tuple[str, str]] = []
    for key in sorted(node):
        if key.startswith("$"):
            continue
        child = node[key]
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(child, dict) and "$value" in child:
            out.append((path, str(child["$value"])))
        elif isinstance(child, dict):
            out.extend(flatten(child, path))
    return out


def to_scss_variable(path: str) -> str:
    return "$" + path.replace(".", "-").replace("_", "-").lower()


def to_css_custom_property(path: str) -> str:
    return "--fix-" + path.replace(".", "-").replace("_", "-").lower()


def validate(tree: dict) -> None:
    groups = [k for k in tree if not k.startswith("$")]
    required = {"color", "dimension", "typography", "shadow", "breakpoint"}
    missing = required - set(groups)
    if missing:
        raise SystemExit(f"token source invalid: missing groups {sorted(missing)}")
    for group in groups:
        if "$type" not in tree[group]:
            raise SystemExit(f"token source invalid: group {group!r} has no $type")
    # TR-07/DE-17: the Bengali font stack is a first-class token, not a fallback.
    fonts = tree["typography"]["font"]
    if "bengali" not in fonts or "family" not in fonts["bengali"]:
        raise SystemExit("token source invalid: typography.font.bengali.family missing (TR-07)")
    if "Noto Sans Bengali" not in str(fonts["bengali"]["family"].get("$value", "")):
        raise SystemExit("token source invalid: Bengali family must be Noto Sans Bengali (UX-007)")


def main() -> int:
    with open(SOURCE, encoding="utf-8") as handle:
        tree = json.load(handle)
    validate(tree)

    flat = flatten(tree)

    # R1 — SCSS variables + CSS custom properties for the Odoo asset bundler.
    scss = [HEADER, ""]
    css = [
        "/* " + " ".join(line.removeprefix("// ") for line in HEADER.strip().splitlines()) + " */",
        "",
    ]
    for path, value in flat:
        note = ""
        node = tree
        for part in path.split("."):
            node = node[part]
        if "$description" in node:
            note = f"  // {node['$description']}"
        scss.append(f"{to_scss_variable(path)}: {value};{note}")
        css.append(f"{to_css_custom_property(path)}: {value};")
    scss.append("")
    # NB: the :root bridge emits VALUES, not $refs — Sass preserves custom
    # property values verbatim ($refs would leak as literals; found by the
    # PP0 audit: the bridge had been dead CSS since Phase 4).
    scss.append(":root {")
    scss.extend(f"    {to_css_custom_property(path)}: {value};" for path, value in flat)
    scss.append("}")
    scss.append("")

    # R2 — TypeScript realisation (typed, readonly).
    ts = [HEADER.replace("// ", "// "), ""]
    ts.append("export const tokens = {")
    for path, value in flat:
        ts.append(f'  "{path}": {json.dumps(value, ensure_ascii=False)},')
    ts.append("} as const;")
    ts.append("")
    ts.append("export type TokenPath = keyof typeof tokens;")
    ts.append("export const token = (path: TokenPath): string => tokens[path];")
    ts.append("")

    # Conformance input — the flat map the CFM suite asserts against.
    flat_doc = {
        "$schema": "generated — conformance input (CFM-02 value parity)",
        "source": str(SOURCE.relative_to(REPO)).replace("\\", "/"),
        "count": len(flat),
        "tokens": dict(flat),
    }

    # R4 — Dart realisation (Flutter fix_ui theme). Dart identifiers cannot
    # contain dots; the canonical path is preserved in a doc comment per
    # constant so cross-runtime tracing stays possible (UX-001 §3.2).
    dart_header = HEADER.replace("// GENERATED", "// GENERATED").replace(
        "tokens.json (DTCG", "tokens.json (DTCG"
    )
    dart = [dart_header, "", "/// fix_ui theme constants — the R4 realisation.", "library;", ""]
    for path, value in flat:
        const = "t_" + path.replace(".", "_").replace("-", "_").lower()
        dart.append(f"/// {path}")
        dart.append(f"const String {const} = {json.dumps(value, ensure_ascii=False)};")
    dart.append("")

    # R6 — Next.js CSS custom properties: every flat token on :root, plus
    # semantic aliases (light values in :root, dark overrides under
    # html[data-theme="dark"]) and density row-height switching. Components
    # consume --fix-<alias>; the raw --fix-<token-path> properties remain
    # available for one-off reads (parity with tokens.generated.ts).
    flat_map = dict(flat)
    css6 = [
        "/* " + " ".join(line.removeprefix("// ") for line in HEADER.strip().splitlines()) + " */",
        "/* R6 realisation — Next.js portals. Semantic aliases + dark/density variants. */",
        "",
        ":root {",
    ]
    css6.extend(f"    {to_css_custom_property(path)}: {value};" for path, value in flat)
    css6.append("}")
    css6.append("")
    css6.append("/* Semantic aliases — light theme (values resolved from the token source). */")
    css6.append(":root {")
    for alias, light, _dark in SEMANTIC_ALIASES:
        if light not in flat_map:
            raise SystemExit(f"token source invalid: alias {alias!r} light path {light!r} missing")
        css6.append(f"    --fix-{alias}: {flat_map[light]};")
    css6.append(f"    --fix-row-h: {flat_map['dimension.density.row-cozy']};")
    css6.append("}")
    css6.append("")
    dark_lines = []
    for _alias, _light, dark in SEMANTIC_ALIASES:
        if dark is None:
            continue
        if dark not in flat_map:
            raise SystemExit(f"token source invalid: alias {_alias!r} dark path {dark!r} missing")
        dark_lines.append(f"    --fix-{_alias}: {flat_map[dark]};")
    if dark_lines:
        css6.append('html[data-theme="dark"] {')
        css6.extend(dark_lines)
        css6.append("}")
        css6.append("")
    for density in ("compact", "cozy", "relaxed"):
        path = f"dimension.density.row-{density}"
        css6.append(f'html[data-density="{density}"] {{ --fix-row-h: {flat_map[path]}; }}')
    css6.append("")
    # Font stacks composed from the font tokens (family + fallback, quoted
    # as the source stores them). The app layer may prepend a next/font var.
    css6.append(":root {")
    css6.append(f"    --fix-font-latin: {flat_map['typography.font.latin.family']};")
    css6.append(f"    --fix-font-latin-fb: {flat_map['typography.font.latin.fallback']};")
    css6.append(f"    --fix-font-bn: {flat_map['typography.font.bengali.family']};")
    css6.append(f"    --fix-font-bn-fb: {flat_map['typography.font.bengali.fallback']};")
    css6.append(
        f"    --fix-font-mono: {flat_map['typography.font.mono.family']}, {flat_map['typography.font.mono.fallback']};"
    )
    css6.append(
        f"    --fix-font-display: {flat_map['typography.font.display.family']}, {flat_map['typography.font.display.fallback']};"
    )
    css6.append("}")
    css6.append("")

    GENERATED["scss"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["scss"].write_text("\n".join(scss), encoding="utf-8", newline="\n")
    GENERATED["css"].write_text("\n".join(css), encoding="utf-8", newline="\n")
    GENERATED["next_css"].write_text("\n".join(css6), encoding="utf-8", newline="\n")
    GENERATED["ts"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["ts"].write_text("\n".join(ts), encoding="utf-8", newline="\n")
    GENERATED["dart"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["dart"].write_text("\n".join(dart), encoding="utf-8", newline="\n")
    GENERATED["flat"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["flat"].write_text(
        json.dumps(flat_doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )

    print(
        f"design-tokens: {len(flat)} tokens -> "
        + ", ".join(str(p.relative_to(REPO)).replace("\\", "/") for p in GENERATED.values())
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

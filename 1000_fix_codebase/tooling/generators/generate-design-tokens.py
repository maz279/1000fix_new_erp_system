#!/usr/bin/env python3
"""generate-design-tokens — P04-M07-T02/T04/T07 (DSY-01, UX-001 §5.3).

"One token source, one component contract, five realisations, one
conformance suite." This executable is the only writer of every realisation:

  libs/ts/ui/src/tokens/tokens.json          SOURCE (the only authored file)
  addons/platform/cd_design_tokens/static/src/tokens.scss   R1 (Odoo bundler)
  libs/ts/ui/src/tokens/tokens.generated.ts                 R2 (Next.js portals)
  addons/platform/cd_design_tokens/static/src/tokens.css    R3 (QWeb reports)
  tooling/design-system/tokens.flat.json                    conformance input

No runtime authors a value; every runtime consumes a generated artefact.
Re-running this script with an unchanged source produces byte-identical
output (deterministic ordering, LF endings, no timestamps).

Exit: 0 regenerated / 1 source invalid.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "libs/ts/ui/src/tokens/tokens.json"
GENERATED = {
    "scss": REPO / "addons/platform/cd_design_tokens/static/src/tokens.scss",
    "css": REPO / "addons/platform/cd_design_tokens/static/src/tokens.css",
    "ts": REPO / "libs/ts/ui/src/tokens/tokens.generated.ts",
    "flat": REPO / "tooling/design-system/tokens.flat.json",
}

HEADER = """// GENERATED by tooling/generators/generate-design-tokens.py — DO NOT EDIT.
// Source of truth: libs/ts/ui/src/tokens/tokens.json (DTCG Format Module 2025.10).
// Any value change happens in the source, then `py tooling/generators/generate-design-tokens.py`.
"""


def flatten(node: dict, prefix: str = "") -> list[tuple[str, str]]:
    """DTCG tree -> ordered [(token_path, value)]; $-keys are metadata."""
    out: list[tuple[str, str]] = []
    for key in sorted(node):
        if key.startswith("$"):
            continue
        child = node[key]
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(child, dict) and "$value" in child:
            out.append((path, str(child["$value"])))
        elif isinstance(child, dict):
            out.extend(flatten(child, path))
    return out


def to_scss_variable(path: str) -> str:
    return "$" + path.replace(".", "-").replace("_", "-").lower()


def to_css_custom_property(path: str) -> str:
    return "--fix-" + path.replace(".", "-").replace("_", "-").lower()


def validate(tree: dict) -> None:
    groups = [k for k in tree if not k.startswith("$")]
    required = {"color", "dimension", "typography", "shadow", "breakpoint"}
    missing = required - set(groups)
    if missing:
        raise SystemExit(f"token source invalid: missing groups {sorted(missing)}")
    for group in groups:
        if "$type" not in tree[group]:
            raise SystemExit(f"token source invalid: group {group!r} has no $type")
    # TR-07/DE-17: the Bengali font stack is a first-class token, not a fallback.
    fonts = tree["typography"]["font"]
    if "bengali" not in fonts or "family" not in fonts["bengali"]:
        raise SystemExit("token source invalid: typography.font.bengali.family missing (TR-07)")
    if "Noto Sans Bengali" not in str(fonts["bengali"]["family"].get("$value", "")):
        raise SystemExit("token source invalid: Bengali family must be Noto Sans Bengali (UX-007)")


def main() -> int:
    with open(SOURCE, encoding="utf-8") as handle:
        tree = json.load(handle)
    validate(tree)

    flat = flatten(tree)

    # R1 — SCSS variables + CSS custom properties for the Odoo asset bundler.
    scss = [HEADER, ""]
    css = ["/* " + " ".join(line.removeprefix("// ") for line in HEADER.strip().splitlines()) + " */", ""]
    for path, value in flat:
        note = ""
        node = tree
        for part in path.split("."):
            node = node[part]
        if "$description" in node:
            note = f"  // {node['$description']}"
        scss.append(f"{to_scss_variable(path)}: {value};{note}")
        css.append(f"{to_css_custom_property(path)}: {value};")
    scss.append("")
    scss.append(":root {")
    scss.extend(f"    {to_css_custom_property(path)}: {to_scss_variable(path)};" for path, _ in flat)
    scss.append("}")
    scss.append("")

    # R2 — TypeScript realisation (typed, readonly).
    ts = [HEADER.replace("// ", "// "), ""]
    ts.append("export const tokens = {")
    for path, value in flat:
        ts.append(f'  "{path}": {json.dumps(value, ensure_ascii=False)},')
    ts.append("} as const;")
    ts.append("")
    ts.append("export type TokenPath = keyof typeof tokens;")
    ts.append("export const token = (path: TokenPath): string => tokens[path];")
    ts.append("")

    # Conformance input — the flat map the CFM suite asserts against.
    flat_doc = {
        "$schema": "generated — conformance input (CFM-02 value parity)",
        "source": str(SOURCE.relative_to(REPO)).replace("\\", "/"),
        "count": len(flat),
        "tokens": {path: value for path, value in flat},
    }

    GENERATED["scss"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["scss"].write_text("\n".join(scss), encoding="utf-8", newline="\n")
    GENERATED["css"].write_text("\n".join(css), encoding="utf-8", newline="\n")
    GENERATED["ts"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["ts"].write_text("\n".join(ts), encoding="utf-8", newline="\n")
    GENERATED["flat"].parent.mkdir(parents=True, exist_ok=True)
    GENERATED["flat"].write_text(
        json.dumps(flat_doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )

    print(f"design-tokens: {len(flat)} tokens -> "
          + ", ".join(str(p.relative_to(REPO)).replace('\\', '/') for p in GENERATED.values()))
    return 0


if __name__ == "__main__":
    sys.exit(main())

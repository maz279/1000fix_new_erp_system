#!/usr/bin/env python3
"""generate-portal-nav — R2 portal shell navigation payload (asset 2 slice).

Emits libs/ts/ui/src/nav.generated.ts from contracts/nav/registry.json:
areas -> modules -> groups -> screens, bilingual (en/bn), slim enough for
the P01 critical-path budget (desc / kpis / freg / cross / journeys are
dropped; reports+forms collapse to counts). Deterministic: LF endings,
no timestamps, sorted as the registry is ordered.

Exit: 0 regenerated / 1 registry invalid.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "contracts/nav/registry.json"
DEST = REPO / "libs/ts/ui/src/nav.generated.ts"

HEADER = """// GENERATED by tooling/generators/generate-portal-nav.py — DO NOT EDIT.
// Source of truth: contracts/nav/registry.json (the frozen prototype nav,
// PP0-M03-T01). ERP entries deep-link to the P03 back-office workspace;
// portal sections are supplied by each app (the registry has no per-portal
// menus). Bilingual en/bn everywhere (DE-17).
"""


def main() -> int:
    reg = json.loads(SOURCE.read_text(encoding="utf-8"))
    modules_by_id = {m["id"]: m for m in reg["modules"]}

    areas = []
    n_groups = n_screens = 0
    for area in reg["areas"]:
        mods = []
        for mid in area.get("modules", []):
            m = modules_by_id[mid]
            groups = []
            for g in m["groups"]:
                screens = [
                    {"id": s["id"], "en": s["en"], "bn": s.get("bn", s["en"]), "t": s.get("t", "w")}
                    for s in g["screens"]
                ]
                n_groups += 1
                n_screens += len(screens)
                groups.append({"en": g["en"], "screens": screens})
            mods.append(
                {
                    "id": m["id"],
                    "en": m["en"],
                    "bn": m.get("bn", m["en"]),
                    "icon": m.get("icon", "▦"),
                    "rail": m.get("rail", "platform"),
                    "groups": groups,
                    "reportCount": len(m.get("reports", [])),
                    "formCount": len(m.get("forms", [])),
                }
            )
        areas.append(
            {
                "id": area["id"],
                "key": area["key"],
                "en": area["en"],
                "bn": area.get("bn", area["en"]),
                "modules": mods,
            }
        )

    expected = reg["counts"]
    if (
        len(areas) != expected["areas"]
        or n_screens != expected["screens"]
        or n_groups != expected["groups"]
    ):
        sys.stderr.write(
            f"registry drift: areas {len(areas)}/{expected['areas']} "
            f"groups {n_groups}/{expected['groups']} screens {n_screens}/{expected['screens']}\n"
        )
        return 1

    lines = [HEADER, ""]
    lines.append("export interface NavScreen { id: string; en: string; bn: string; t: string; }")
    lines.append("export interface NavGroup { en: string; screens: NavScreen[]; }")
    lines.append("export interface NavModule {")
    lines.append("  id: string; en: string; bn: string; icon: string; rail: string;")
    lines.append("  groups: NavGroup[]; reportCount: number; formCount: number;")
    lines.append("}")
    lines.append(
        "export interface NavArea { id: string; key: string; en: string; bn: string; modules: NavModule[]; }"
    )
    lines.append("")
    lines.append("export const navAreas: NavArea[] = [")
    for area in areas:
        lines.append("  {")
        lines.append(f'    id: {json.dumps(area["id"])}, key: {json.dumps(area["key"])},')
        lines.append(
            f'    en: {json.dumps(area["en"], ensure_ascii=False)}, bn: {json.dumps(area["bn"], ensure_ascii=False)},'
        )
        lines.append("    modules: [")
        for m in area["modules"]:
            lines.append("      {")
            lines.append(
                f'        id: {json.dumps(m["id"])}, en: {json.dumps(m["en"], ensure_ascii=False)},'
            )
            lines.append(
                f'        bn: {json.dumps(m["bn"], ensure_ascii=False)}, icon: {json.dumps(m["icon"])}, rail: {json.dumps(m["rail"])},'
            )
            lines.append(f'        reportCount: {m["reportCount"]}, formCount: {m["formCount"]},')
            lines.append("        groups: [")
            for g in m["groups"]:
                scr = ", ".join(
                    f'{{ id: {json.dumps(s["id"])}, en: {json.dumps(s["en"], ensure_ascii=False)}, '
                    f'bn: {json.dumps(s["bn"], ensure_ascii=False)}, t: {json.dumps(s["t"])} }}'
                    for s in g["screens"]
                )
                lines.append(
                    f'          {{ en: {json.dumps(g["en"], ensure_ascii=False)}, screens: [{scr}] }},'
                )
            lines.append("        ],")
            lines.append("      },")
        lines.append("    ],")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    lines.append(
        "export const navCounts = "
        + json.dumps(
            {
                "areas": len(areas),
                "modules": len(modules_by_id),
                "groups": n_groups,
                "screens": n_screens,
            },
            ensure_ascii=False,
        )
        + ";"
    )
    lines.append("")

    DEST.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    size = DEST.stat().st_size
    print(
        f"portal-nav: {len(areas)} areas / {len(modules_by_id)} modules / {n_groups} groups / {n_screens} screens -> {DEST.relative_to(REPO)} ({size//1024} KB raw)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

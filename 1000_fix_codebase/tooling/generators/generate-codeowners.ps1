# =============================================================================
# generate-codeowners.ps1 - P02-M03-T08
# Generates CODEOWNERS from tooling/cd-register.yaml (BE-005 section 6).
# GENERATED OUTPUT IS NEVER HAND-EDITED: ownership changes go through BE-005
# under change control, then this generator re-runs.
#
# Mapping rules (unit -> owning directory + squad placeholder):
#   M-units  -> addons/domain/<category>/ (category from the unit's category
#              block in BE-005 section 6 headings, simplified here to a
#              category map maintained below) ; platform units (M28-M30,
#              M64, M65...) whose items are cd_* platform modules ->
#              addons/platform/<technical-name>
#   P-units  -> apps/web/<portal> (portal CD items) or apps/mobile/<app>
#   Service-typed items -> services/<technical-name>
# Squad names come from roadmap 0.10.1 with @1000fix- placeholders until the
# programme tool exists (P01-M01-T06 names the leads).
# =============================================================================
[CmdletBinding()]
param([string]$OutFile = '')
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)   # repo root
$yamlPath = Join-Path $root 'tooling\cd-register.yaml'
if (-not (Test-Path $yamlPath)) { Write-Error 'tooling/cd-register.yaml not found - run generate-cd-register.ps1 first' }
if ($OutFile -eq '') { $OutFile = Join-Path $root 'CODEOWNERS' }

# Unit -> category directory (BE-004 section 4 layer-4 categories)
$unitCategory = @{
    'M01'='a_service_delivery';'M02'='a_service_delivery';'M03'='a_service_delivery';'M04'='a_service_delivery';'M05'='a_service_delivery'
    'M09'='b_customer_engagement';'M10'='b_customer_engagement';'M11'='b_customer_engagement';'M12'='b_customer_engagement';'M27'='b_customer_engagement';'M32'='b_customer_engagement'
    'M08'='c_commercial';'M20'='c_commercial';'M37'='c_commercial';'M40'='c_commercial';'M53'='c_commercial'
    'M13'='d_circular';'M14'='d_circular';'M43'='d_circular';'M44'='d_circular'
    'M15'='e_supply_chain';'M16'='e_supply_chain';'M17'='e_supply_chain';'M41'='e_supply_chain';'M42'='e_supply_chain'
    'M06'='f_asset_facilities';'M07'='f_asset_facilities';'M18'='f_asset_facilities';'M45'='f_asset_facilities';'M46'='f_asset_facilities';'M47'='f_asset_facilities';'M48'='f_asset_facilities';'M49'='f_asset_facilities';'M54'='f_asset_facilities'
    'M19'='g_finance';'M21'='g_finance';'M50'='g_finance';'M51'='g_finance';'M52'='g_finance';'M55'='g_finance';'M56'='g_finance';'M57'='g_finance'
    'M22'='h_people';'M23'='h_people'
    'M24'='i_governance';'M25'='i_governance';'M58'='i_governance';'M59'='i_governance';'M60'='i_governance';'M61'='i_governance';'M66'='i_governance';'M67'='i_governance'
    'M26'='j_data_analytics';'M62'='j_data_analytics';'M63'='j_data_analytics'
    'M28'='k_platform';'M29'='k_platform';'M30'='k_platform';'M31'='k_platform';'M33'='k_platform';'M34'='k_platform';'M35'='k_platform';'M36'='k_platform';'M38'='k_platform';'M39'='k_platform';'M64'='k_platform';'M65'='k_platform'
}
# Category -> squad (roadmap 0.10.1 six squads)
$categorySquad = @{
    'a_service_delivery'='service-delivery';'f_asset_facilities'='service-delivery'
    'c_commercial'='commercial-finance';'g_finance'='commercial-finance'
    'e_supply_chain'='data-integration';'j_data_analytics'='data-integration'
    'b_customer_engagement'='experience';'d_circular'='experience'
    'h_people'='people-governance';'i_governance'='people-governance'
    'k_platform'='platform'
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# CODEOWNERS - GENERATED FILE. DO NOT HAND-EDIT.')
$lines.Add('# Generated by tooling/generators/generate-codeowners.ps1 from')
$lines.Add('# tooling/cd-register.yaml (BE-005 section 6, P02-M03-T08).')
$lines.Add('# Regenerate: powershell -File tooling/generators/generate-codeowners.ps1')
$lines.Add('# Hand edits will be overwritten. Ownership changes go through BE-005.')
$lines.Add('')
$lines.Add('# Root fallback until the programme tool names the leads (P01-M01-T06):')
$lines.Add('/*                            @1000fix-platform-lead')
$lines.Add('')

$current = $null   # current item
$items = @()
foreach ($raw in [System.IO.File]::ReadAllLines($yamlPath)) {
    if ($raw -match '^- id: (CD-\S+)') { if ($current) { $items += $current }; $current = [ordered]@{ id = $Matches[1]; name = ''; type = ''; unit = '' } ; continue }
    if ($current) {
        if ($raw -match '^  unit: (\S+)') { $current.unit = $Matches[1] }
        elseif ($raw -match '^  name: (.+)$') { $current.name = $Matches[1].Trim() -replace '`','' }
        elseif ($raw -match '^  type: "(.+)"$') { $current.type = $Matches[1] }
    }
}
if ($current) { $items += $current }

$emitted = @{}
foreach ($it in $items) {
    $unit = $it.unit; $tech = $it.name
    if (-not $unit -or -not $tech -or $tech -eq '-') { continue }
    $dir = $null
    if ($it.type -match 'Odoo') {
        if ($unitCategory[$unit] -eq 'k_platform' -and $tech -match '^cd_') { $dir = "addons/platform/$tech" }
        elseif ($unitCategory[$unit]) { $dir = "addons/domain/$($unitCategory[$unit])/$tech" }
    } elseif ($it.type -match 'Service') {
        $dir = "services/$tech"
    } elseif ($it.type -match 'application|app' -or $it.type -match 'Next') {
        $dir = "apps/web/$tech"
    } elseif ($it.type -match 'Mobile') {
        $dir = "apps/mobile/$tech"
    }
    if (-not $dir) { continue }
    if ($emitted[$dir]) { continue }
    $emitted[$dir] = $true
    $squad = if ($unitCategory[$unit] -and $categorySquad[$unitCategory[$unit]]) { $categorySquad[$unitCategory[$unit]] } else { 'platform' }
    $lines.Add(("/{0,-52} @1000fix-{1}" -f $dir, $squad))
}
[System.IO.File]::WriteAllLines($OutFile, $lines)
Write-Host ("CODEOWNERS written: {0} ({1} ownership rows + fallback)" -f $OutFile, ($emitted.Keys.Count))

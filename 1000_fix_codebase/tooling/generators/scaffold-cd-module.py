#!/usr/bin/env python3
"""scaffold-cd-module - generates a `cd_` module skeleton (doctor check 7).

FF-16-native: the generator REFUSES a module name whose CD identifier is not
in tooling/cd-register.yaml (BE-005 section 6). A scaffold outside the
register cannot be created at all - which is exactly the membership check,
applied at birth rather than at review.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
REGISTER = REPO_ROOT / "tooling" / "cd-register.yaml"

MANIFEST_TEMPLATE = '''# Generated by tooling/generators/scaffold-cd-module.py - do not remove header.
{{
    "name": "{tech}",
    "version": "19.0.0.1.0",
    "summary": "{cd_id} - {cd_id} scaffold (fill in)",
    "depends": ["base"],
    "data": [],
    "installable": True,
    "application": False,
    "license": "LGPL-3",
}}
'''

INIT_TEMPLATE = '''# {tech} - CD item {cd_id}. Generated scaffold.
from odoo import models  # noqa: F401  (remove when first model lands)
'''


def register_has(cd_id: str) -> bool:
    if not REGISTER.exists():
        print("scaffold: FAIL - cd-register.yaml not found; run generate-cd-register.ps1")
        return False
    return any(cd_id in line for line in REGISTER.read_text(encoding="utf-8").splitlines())


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: scaffold-cd-module.py CD-M01-01 cd_tech_name")
        return 2
    cd_id, tech = argv[1], argv[2]
    if not cd_id.startswith("CD-") or not tech.startswith("cd_"):
        print("scaffold: FAIL - expected CD-<UNIT>-<nn> and a cd_ technical name (AS-04)")
        return 2
    if not register_has(cd_id):
        print(f"scaffold: FAIL - {cd_id} is NOT in BE-005 section 6 (FF-16/CDR-08).")
        print("  remedy: pick a registered identifier, or issue the new item through BE-005 change control.")
        return 1
    target = REPO_ROOT / "addons" / "platform" / tech
    if target.exists():
        print(f"scaffold: {target} already exists")
        return 0
    target.mkdir(parents=True)
    (target / "__manifest__.py").write_text(MANIFEST_TEMPLATE.format(tech=tech, cd_id=cd_id), encoding="utf-8")
    (target / "__init__.py").write_text(INIT_TEMPLATE.format(tech=tech, cd_id=cd_id), encoding="utf-8")
    (target / "models").mkdir()
    (target / "models" / "__init__.py").write_text("", encoding="utf-8")
    (target / "views").mkdir()
    print(f"scaffold: created {target} for {cd_id}")
    print("next: make odoo-conf && make upgrade MODULE=" + tech)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

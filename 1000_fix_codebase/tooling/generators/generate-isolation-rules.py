#!/usr/bin/env python3
"""generate-isolation-rules - AS-03 record-rule isolation for every transactional model.

R01 re-audit 2026-10-22 (pentest A01-05): 174 transactional models carried
company_id and operating_unit_id COLUMNS, but 167 had no multi-company
ir.rule and none had an operating-unit ir.rule - a column isolates nothing,
so any internal user could read every company's and every branch's records.

For each first-party addon this writes `security/fix_isolation_rules.xml`
(and lists it in the manifest `data`) with, per transactional model it
DEFINES (`_name` in its models/, not an FF-21 exempt master/config model):

  * a GLOBAL multi-company rule - the standard Odoo isolation:
      ['|', ('company_id', '=', False), ('company_id', 'in', company_ids)]
  * an operating-unit rule for INTERNAL users (base.group_user), the OCA
    operating_unit pattern (`operating_unit_ids` = the user's allowed units;
    members of operating_unit.group_manager_operating_unit are allowed all):
      ['|', ('operating_unit_id', '=', False),
            ('operating_unit_id', 'in', operating_unit_ids)]
    Group-scoped, not global: portal/public users are never in an operating
    unit, and their own record rules (own orders, own devices...) govern them.

A model that already has a hand-written rule restricting on the same column
is left alone (that rule is the module owner's decision). The output is
deterministic: --check regenerates in memory and fails on any drift, so a
new transactional model cannot merge without its isolation (FF-47).

Usage: python tooling/generators/generate-isolation-rules.py [--check] [--addons DIR]
Exit 0 written/clean - 1 drift or missing (with --check) - 2 manifest not editable.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RULES_FILE = "security/fix_isolation_rules.xml"
REGISTRY_CHECK = ROOT / "tooling" / "fitness" / "check_model_registry.py"

RULE_RECORD = re.compile(r"<record\b[^>]*\bmodel=\"ir\.rule\"[^>]*>(.*?)</record>", re.DOTALL)
RULE_MODEL_REF = re.compile(r"name=\"model_id\"[^>]*\bref=\"([^\"]+)\"")
RULE_DOMAIN = re.compile(
    r"name=\"domain_force\"(?:[^>]*\beval=\"([^\"]*)\"[^>]*/?>|[^>]*>(.*?)</field>)", re.DOTALL
)

COMPANY_DOMAIN = "['|', ('company_id', '=', False), ('company_id', 'in', company_ids)]"
OU_DOMAIN = "['|', ('{f}', '=', False), ('{f}', 'in', operating_unit_ids)]"

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by tooling/generators/generate-isolation-rules.py - DO NOT EDIT.
  AS-03 record-rule isolation (R01 re-audit 2026-10-22, pentest A01-05):
  every transactional model of this module is restricted to the user's
  allowed companies (global rule) and, for internal users, to their allowed
  operating units (OCA operating_unit; operating-unit managers see all).
  Regenerate: python tooling/generators/generate-isolation-rules.py
-->
<odoo>
"""


@dataclass
class ModelFacts:
    name: str
    company: bool = False
    ou_field: str | None = None


@dataclass
class ModulePlan:
    path: Path
    models: list[ModelFacts] = field(default_factory=list)


def load_exempt_models() -> set[str]:
    spec = importlib.util.spec_from_file_location("check_model_registry", REGISTRY_CHECK)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {REGISTRY_CHECK}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return set(module.EXEMPT_MODELS)


def _is_concrete_model(cls: ast.ClassDef) -> bool:
    return any(
        isinstance(b, ast.Attribute)
        and isinstance(b.value, ast.Name)
        and b.value.id == "models"
        and b.attr == "Model"
        for b in cls.bases
    )


def _field_call(value: ast.expr) -> tuple[str, dict[str, ast.expr]] | None:
    """`fields.X(...)` -> ("X", keywords), else None."""
    if (
        isinstance(value, ast.Call)
        and isinstance(value.func, ast.Attribute)
        and isinstance(value.func.value, ast.Name)
        and value.func.value.id == "fields"
    ):
        return value.func.attr, {k.arg: k.value for k in value.keywords if k.arg}
    return None


def _searchable(kw: dict[str, ast.expr]) -> bool:
    """A rule domain needs a stored or related (hence searchable) field."""

    def const(key: str) -> object:
        node = kw.get(key)
        return node.value if isinstance(node, ast.Constant) else None

    if const("store") is False:
        return False
    return not ("compute" in kw and const("store") is not True and "search" not in kw)


def model_facts(cls: ast.ClassDef) -> ModelFacts | None:
    """Facts of a class that DEFINES a model (`_name` not merely re-inherited)."""
    name, inherits = None, set()
    fields_found: dict[str, tuple[str, dict[str, ast.expr]]] = {}
    for stmt in cls.body:
        if not (
            isinstance(stmt, ast.Assign)
            and len(stmt.targets) == 1
            and isinstance(stmt.targets[0], ast.Name)
        ):
            continue
        target, value = stmt.targets[0].id, stmt.value
        if target == "_name" and isinstance(value, ast.Constant) and isinstance(value.value, str):
            name = value.value
        elif target == "_inherit":
            items = value.elts if isinstance(value, ast.List | ast.Tuple) else [value]
            inherits |= {i.value for i in items if isinstance(i, ast.Constant)}
        elif (call := _field_call(value)) is not None:
            fields_found[target] = call
    if not name or name in inherits:
        return None
    facts = ModelFacts(name)
    co = fields_found.get("company_id")
    facts.company = bool(co and co[0] == "Many2one" and _searchable(co[1]))
    for fname, ftype in (("operating_unit_id", "Many2one"), ("operating_unit_ids", "Many2many")):
        f = fields_found.get(fname)
        if f and f[0] == ftype and _searchable(f[1]):
            facts.ou_field = fname
            break
    return facts


def existing_rule_domains(addons: Path) -> dict[str, list[str]]:
    """`model_fix_x` -> domains of every hand-written ir.rule (generated file excluded)."""
    rules: dict[str, list[str]] = {}
    for xml in sorted(addons.rglob("*.xml")):
        if "i18n" in xml.parts or xml.as_posix().endswith(RULES_FILE):
            continue
        text = xml.read_text(encoding="utf-8", errors="ignore")
        for body in RULE_RECORD.findall(text):
            ref = RULE_MODEL_REF.search(body)
            if ref:
                dom = RULE_DOMAIN.search(body)
                rules.setdefault(ref.group(1).split(".")[-1], []).append(
                    (dom.group(1) or dom.group(2) or "") if dom else ""
                )
    return rules


def plan(addons: Path, exempt: set[str]) -> dict[str, ModulePlan]:
    existing = existing_rule_domains(addons)
    plans: dict[str, ModulePlan] = {}
    for manifest in sorted(addons.rglob("__manifest__.py")):
        mod = manifest.parent
        mplan = ModulePlan(mod)
        for py in sorted(mod.glob("models/*.py")):
            try:
                tree = ast.parse(py.read_text(encoding="utf-8"))
            except SyntaxError:
                continue
            for cls in (n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)):
                if not _is_concrete_model(cls):
                    continue
                facts = model_facts(cls)
                if not facts or facts.name in exempt:
                    continue
                domains = existing.get("model_" + facts.name.replace(".", "_"), [])
                if any("company_id" in d for d in domains):
                    facts.company = False
                if any("operating_unit" in d for d in domains):
                    facts.ou_field = None
                if facts.company or facts.ou_field:
                    mplan.models.append(facts)
        if mplan.models:
            plans[mod.name] = mplan
    return plans


def render(models: list[ModelFacts]) -> str:
    out = [HEADER]
    for m in sorted(models, key=lambda x: x.name):
        key = m.name.replace(".", "_")
        if m.company:
            out.append(
                f'    <record id="rule_{key}_company" model="ir.rule">\n'
                f'        <field name="name">{m.name}: allowed companies</field>\n'
                f'        <field name="model_id" ref="model_{key}"/>\n'
                f'        <field name="domain_force">{COMPANY_DOMAIN}</field>\n'
                "    </record>\n"
            )
        if m.ou_field:
            out.append(
                f'    <record id="rule_{key}_operating_unit" model="ir.rule">\n'
                f'        <field name="name">{m.name}: allowed operating units (internal users)</field>\n'
                f'        <field name="model_id" ref="model_{key}"/>\n'
                '        <field name="groups" eval="[(4, ref(\'base.group_user\'))]"/>\n'
                f'        <field name="domain_force">{OU_DOMAIN.format(f=m.ou_field)}</field>\n'
                "    </record>\n"
            )
    out.append("</odoo>\n")
    return "".join(out)


DATA_OPEN = re.compile(r"([\"']data[\"']\s*:\s*\[)")


def manifest_with_entry(text: str) -> str | None:
    """The manifest text with RULES_FILE in `data` (unchanged if present), or
    None when no `data` list can be located for a safe edit."""
    if RULES_FILE in text:
        return text
    match = DATA_OPEN.search(text)
    if not match:
        return None
    after = text[match.end() :]
    newline = re.match(r"[ \t]*\n([ \t]*)", after)
    if newline:  # multi-line list: insert as its first line, same indent
        indent = newline.group(1)
        pos = match.end() + newline.end() - len(indent)
        return text[:pos] + f'{indent}"{RULES_FILE}",\n' + text[pos:]
    return text[: match.end()] + f'"{RULES_FILE}", ' + text[match.end() :]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    ap.add_argument("--addons", default=str(ROOT / "addons"))
    args = ap.parse_args(argv)
    addons = Path(args.addons)
    plans = plan(addons, load_exempt_models())

    drift: list[str] = []
    unwritable: list[str] = []
    n_company = sum(m.company for p in plans.values() for m in p.models)
    n_ou = sum(bool(m.ou_field) for p in plans.values() for m in p.models)
    for name, mplan in sorted(plans.items()):
        target = mplan.path / RULES_FILE
        content = render(mplan.models)
        manifest = mplan.path / "__manifest__.py"
        mtext = manifest.read_text(encoding="utf-8")
        new_manifest = manifest_with_entry(mtext)
        if new_manifest is None:
            unwritable.append(f"{name}: no `data` list in __manifest__.py")
            continue
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current != content or new_manifest != mtext:
            drift.append(name)
            if not args.check:
                target.parent.mkdir(exist_ok=True)
                target.write_text(content, encoding="utf-8", newline="\n")
                manifest.write_text(new_manifest, encoding="utf-8", newline="\n")
    # A generated file whose models all gained hand-written rules (or left) is stale.
    for stale in sorted(addons.rglob(RULES_FILE)):
        if stale.parent.parent.name not in plans:
            drift.append(f"{stale.parent.parent.name} (stale {RULES_FILE})")
            if not args.check:
                stale.unlink()

    summary = f"{len(plans)} modules, {n_company} company rules, {n_ou} operating-unit rules"
    if unwritable:
        print("generate-isolation-rules: FAIL - " + "; ".join(unwritable))
        return 2
    if args.check:
        if drift:
            print(
                f"generate-isolation-rules: FAIL - {len(drift)} module(s) missing or drifted "
                f"isolation rules: {', '.join(drift[:10])}"
                + (f" ... {len(drift) - 10} more" if len(drift) > 10 else "")
                + "\n  remedy: python tooling/generators/generate-isolation-rules.py"
            )
            return 1
        print(f"generate-isolation-rules: OK - {summary}, no drift")
        return 0
    print(f"generate-isolation-rules: wrote {len(drift)} module(s) - {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env node
/**
 * export-fragment-nav — the SHIPPED navigation truth, exported for the registry.
 *
 * The registry generator (generate-nav-registry.py) parses the frozen PP0
 * prototype payloads. The workspace, however, renders the SHIPPED fragments
 * (static/src/<area>/<mod>.js) — capture-pass screens added after the
 * prototype never reached contracts/nav/registry.json, so the mega menu,
 * Tell-ME and the Report Center could not see them (A10 deep audit 2026-11-23,
 * D-A10-7).
 *
 * This exporter imports each shipped fragment (they are plain ES modules with
 * no imports of their own — verified) and writes contracts/nav/fragments.json.
 * The Python generator overlays the modules present in that file onto its
 * prototype parse, so the registry describes what actually ships and FF-38
 * still proves freshness (regeneration is byte-identical).
 *
 * Adding an area = add its module files to FRAGMENTS below.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..");
const OUT = resolve(REPO, "contracts", "nav", "fragments.json");

// The A10 capture-pass fragments (deep audit 2026-11-23). Extend per area.
const FRAGMENTS = [
  ["M23", "addons/platform/cd_p03_portal/static/src/a10/m23.js"],
  ["M24", "addons/platform/cd_p03_portal/static/src/a10/m24.js"],
  ["M60", "addons/platform/cd_p03_portal/static/src/a10/m60.js"],
  ["M61", "addons/platform/cd_p03_portal/static/src/a10/m61.js"],
];

async function loadModule(relPath) {
  const source = readFileSync(resolve(REPO, relPath), "utf8");
  const url = "data:text/javascript;base64," + Buffer.from(source, "utf8").toString("base64");
  return import(url);
}

function reportNames(freg) {
  const names = new Set();
  for (const row of freg?.sub || []) {
    const detail = row[3];
    for (const name of (detail && detail.reports) || []) names.add(name);
  }
  return [...names];
}

const modules = {};
for (const [code, relPath] of FRAGMENTS) {
  const mod = await loadModule(relPath);
  const M = mod.MODULE;
  if (!M) throw new Error(`${relPath}: MODULE export missing`);
  modules[code] = {
    en: M.en,
    bn: M.bn,
    icon: M.icon || "",
    desc: M.desc || "",
    groups: (M.groups || []).map((g) => ({
      en: g.en,
      screens: (g.screens || []).map((s) => ({ id: s.id, en: s.en, bn: s.bn, t: s.t || "g" })),
    })),
    forms: [...(M.forms || [])],
    reports: reportNames(M.freg),
    cross: [...(M.cross || [])],
    // the registry keeps the TRIPLE (id, name, count); the fragment's 4th
    // element (model/cols/screens/reports/forms) is runtime detail
    freg: {
      src: M.freg?.src ?? 0,
      sub: (M.freg?.sub || []).map((r) => [r[0], r[1], r[2]]),
    },
    kpis: [...(M.kpis || [])],
  };
}

const payload = {
  "$note":
    "GENERATED by tooling/generators/export-fragment-nav.mjs from the SHIPPED fragments. " +
    "generate-nav-registry.py overlays these modules onto the prototype parse.",
  modules,
};
writeFileSync(OUT, JSON.stringify(payload, null, 1) + "\n", "utf8");

let screens = 0;
let groups = 0;
let forms = 0;
let reports = 0;
for (const m of Object.values(modules)) {
  groups += m.groups.length;
  screens += m.groups.reduce((n, g) => n + g.screens.length, 0);
  forms += m.forms.length;
  reports += m.reports.length;
}
console.log(
  `fragments.json: ${Object.keys(modules).length} modules · ${groups} groups · ${screens} screens · ` +
    `${forms} forms · ${reports} reports`
);
